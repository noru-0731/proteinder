/* ── 하위호환 ─────────────────────────────────────────────────
   원재료 상세(/ingredients/[name])는 **신고 표기 그대로** 들어온다.
   그래서 표기 → 해설 맵을 GROUPS 에서 만들어 둔다.
   원본이 둘이면 언젠가 어긋난다 — 손으로 두 번 적지 않는다. */
export type Note = { what: string; why?: string; group: string; caution?: CautionKey };

export const INGREDIENT_NOTES: Record<string, Note> = Object.fromEntries(
  GROUPS.flatMap((g) =>
    g.entries.flatMap((e) =>
      e.names.map((n) => [n, { what: e.what, why: e.why, group: g.title, caution: e.caution }]),
    ),
  ),
);

export function noteOf(name: string): Note | null {
  return INGREDIENT_NOTES[name] ?? null;
}

/** 사전 상세가 표기 변형(names)까지 보여주기 위해 원본 Entry 를 찾는다 */
export function entryOf(name: string): { entry: Entry; group: Group } | null {
  for (const g of GROUPS)
    for (const e of g.entries) if (e.names.includes(name)) return { entry: e, group: g };
  return null;
}
