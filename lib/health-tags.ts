import type { Product } from "./data";

/* ══════════════════════════════════════════════════════════════════════
   「못 먹을 이유」 태그 — 🔴 우리가 **판정한다**
   ══════════════════════════════════════════════════════════════════════

   커뮤니티에서 실제로 사람들이 손해를 본 순서를 세어 골랐다 (10_작업/09).

     ① 맛 못 먹음   8건  「반통 버렸다」 「2키로 샀다..」   ← 데이터로 못 잡는다
     ② 유당·소화    6건  「유당불내증 있는 사람도 WPC 도전해볼만함」  ← 여기가 이 파일
     ③ 여드름·피부   4건  근거가 약하다. 안 한다

   🔴 **이건 「분포 대비 위치」가 아니라 판정이다.** 지금까지 이 프로젝트가 만든
      점수·등급은 전부 「그래서 뭐?」로 끝났는데, 그 이유는 **평가하지 않으면서
      평가처럼 보이려 했기 때문**이다. 이 태그는 대놓고 판정한다 —
      대신 **판정의 조건을 좁게 잡고 화면에 그대로 적는다.**

   ⚠️ **가장 좁은 조건만 쓴다.** 「WPI 는 유당을 걸러서 괜찮다」는 커뮤니티 통념이지만
      개인차가 크고(같은 갤에 「WPC 도전해볼만함」도 있다), WPI 에도 유당이 미량 남는다.
      게다가 `제트맥스WPI` 처럼 **codes 가 제품명 근거**인 것이 섞여 있어
      신고 원재료로 확인된 값이 아니다. → **우유가 아예 안 들어간 것만** 붙인다.

   ⚠️ **불투명 표기가 하나라도 있으면 안 붙인다.** 「두류가공품」 안에 분유가 있을 수 있다.
      우유 원료가 없는 118건 중 28건이 여기 걸려 **90건만** 남는다.

   실측 (2026-08-06)
     우유 원료가 없고 우유가 숨을 표기도 없음   38건  ← 태그를 붙이는 것
     우유 원료는 없으나 정체불명 표기가 있음    80건  ← 안 붙임
     WPI·MPI 만 있음                    81건  ← 안 붙임 (WPI 에도 유당이 미량 남는다)
*/

const MILK =
  /우유|유청|유단백|카제인|분유|유크림|버터|치즈|락토|유당|산양유|초유|유함유|전지|탈지/;
/** 우유에서 온 원료 코드. 하나라도 있으면 우유가 든 것이다 */
const MILK_CODES = new Set(["유청", "WPI", "WPC", "WPH", "MPI", "MPC", "카제인", "산양유", "초유"]);

/** 이름만으로 내용을 알 수 없어 **우유가 숨어 있을 수 있는** 표기.
 *  `유함유가공품`·`혼합분유` 는 위 MILK 정규식이 이미 잡으므로 여기 없다. */
const MILK_RISKY = new Set([
  "기타가공품",
  "기타 가공품",
  "혼합제제",
  "식품첨가물",
  "식품첨가물혼합제제",
  "효소식품",
  "아미노산혼합제제",
  "기타 코코아가공품",
]);

export type HealthTag = {
  key: string;
  label: string;
  /** 배지에 붙는 한 줄. 왜 이 태그가 붙었는지 */
  why: string;
  tone: "ok";
};

/**
 * 🔴 **「우유가 없다」고 단정하지 않는다.** 우리가 읽은 것은 신고 원재료뿐이고,
 *    제조사 표시란을 본 게 아니다. 알레르기·불내증은 틀리면 사람이 다치므로
 *    화면 문구는 반드시 **「신고된 원재료에서 확인되지 않았다」** 여야 한다.
 */
export function healthTagsOf(p: Product): HealthTag[] {
  const out: HealthTag[] = [];

  /* ⚠️ `p.opaque` 를 쓰면 안 된다 — 그건 **1순위가 불투명한가**(`top_is_opaque`)이지
     「불투명 표기가 하나라도 있는가」가 아니다. 한 번 그렇게 썼다가
     `분리완두단백 … 두류가공품 · 효소식품 · 혼합제제` 인 제품에
     「우유에서 온 것이 하나도 없습니다」가 붙었다.

     ⚠️ 그렇다고 `OPAQUE_NAMES` 전부를 막으면 29건까지 줄어든다.
        **두류·곡류·과채·서류가공품은 식물성이라 우유가 들어갈 여지가 없다.**
        정체를 알 수 없어 **우유가 숨어 있을 수 있는 표기**만 막는다 → 38건. */
  const hidesMilk = p.ings.some((n) => MILK_RISKY.has(n));

  if (p.ings.length > 0 && !hidesMilk) {
    const codes = new Set(p.codes);
    const hasMilk = MILK.test(p.ings.join(" ")) || [...codes].some((c) => MILK_CODES.has(c));
    if (!hasMilk)
      out.push({
        key: "lactose",
        label: "유당불내증 OK",
        why: `신고된 원재료 ${p.ings.length}가지에 우유에서 온 것이 하나도 없습니다.`,
        tone: "ok",
      });
  }

  return out;
}
