/** 화면에 뜨는 순서. 계통 분류 순서지 좋고 나쁨의 순서가 아니다 */
const ORDER = Object.keys(SOURCE_NOTES);

/** 신고서가 유청 세부를 안 갈라 주는 계통. 근거 배지를 붙일 대상이다 */
const WHEY = new Set(["유청", "WPI", "WPC", "WPH"]);

export type ResolvedSource = SourceNote & { code: string; whey: boolean };

/**
 * 제품의 코드 목록을 화면에 적을 순서로 편다.
 * ⚠️ 해설이 없는 코드는 **버린다.** 이름만 덩그러니 적으면 이 카드가 할 말이 없다.
 */
export function sourcesOf(codes: string[]): ResolvedSource[] {
  const has = new Set(codes);
  return ORDER.filter((c) => has.has(c)).map((code) => ({
    ...SOURCE_NOTES[code],
    code,
    whey: WHEY.has(code),
  }));
}
